#!/usr/bin/env python3
"""Turn maps/robocross.pgm into assets for the CARLA Robocross map.

  fence.obj   walls (1.2 m) along the occupied cells of the map
  ground.obj  one quad under the whole map
  arena.xodr  flat OpenDRIVE "road" covering the map: lets generate_opendrive_world() load something
              drivable before the Unreal map is built (world_setup.py --xodr)

The map is an open field bounded by a fence, not a lane network, so no road graph is derived from it.
OBJ coordinates are meters in CARLA axes (x forward, y right = -ROS y, z up); import into Unreal
with a uniform scale of 100 (cm). World frame = map + (2.2, -1.6), as in webots_ros2_suv/maps/README.md.

    python3 tools/robocross_assets.py --map-yaml ../webots_ros2_suv/maps/robocross.yaml --out ../../../carla/assets
"""
import argparse
import os

import cv2
import numpy as np
import yaml

WORLD_FROM_MAP = (2.2, -1.6)
WALL_HEIGHT = 1.2
SIMPLIFY = 0.1   # m, Douglas-Peucker tolerance of the fence outline
MIN_LENGTH = 2.0  # m, shorter outlines are map noise, not fence


def load_occupied(yaml_path):
    with open(yaml_path) as f:
        meta = yaml.safe_load(f)
    img = cv2.imread(os.path.join(os.path.dirname(yaml_path), meta['image']), cv2.IMREAD_GRAYSCALE)
    prob = (255 - img) / 255.0 if meta.get('negate', 0) == 0 else img / 255.0
    return prob > meta['occupied_thresh'], meta['resolution'], meta['origin'][:2]


def to_world(col, row, height, res, origin):
    """Pixel -> CARLA axes (x, y) in meters."""
    x = origin[0] + col * res + WORLD_FROM_MAP[0]
    y = origin[1] + (height - 1 - row) * res + WORLD_FROM_MAP[1]
    return x, -y


def fence_obj(occupied, res, origin):
    height = occupied.shape[0]
    mask = occupied.astype(np.uint8) * 255
    contours, _ = cv2.findContours(mask, cv2.RETR_LIST, cv2.CHAIN_APPROX_NONE)
    verts, faces = [], []
    for contour in contours:
        if cv2.arcLength(contour, True) * res < MIN_LENGTH:
            continue
        poly = cv2.approxPolyDP(contour, SIMPLIFY / res, True)[:, 0, :]
        if len(poly) < 2:
            continue
        pts = [to_world(c, r, height, res, origin) for c, r in poly]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            i = len(verts) + 1
            verts += [(x0, y0, 0.0), (x1, y1, 0.0), (x1, y1, WALL_HEIGHT), (x0, y0, WALL_HEIGHT)]
            faces += [(i, i + 1, i + 2, i + 3), (i + 3, i + 2, i + 1, i)]   # both sides
    return verts, faces


def ground_obj(shape, res, origin):
    h, w = shape
    (x0, y0), (x1, y1) = to_world(0, h - 1, h, res, origin), to_world(w - 1, 0, h, res, origin)
    return [(x0, y0, 0.0), (x1, y0, 0.0), (x1, y1, 0.0), (x0, y1, 0.0)], [(1, 4, 3, 2)]


def write_obj(path, verts, faces):
    with open(path, 'w') as f:
        f.write('# generated by robocross_assets.py\n')
        f.writelines(f'v {x:.3f} {y:.3f} {z:.3f}\n' for x, y, z in verts)
        f.writelines('f ' + ' '.join(map(str, face)) + '\n' for face in faces)


def arena_xodr(shape, res, origin):
    """Straight road along CARLA +x through the map's center, 2 + 2 lanes spanning the map's width."""
    h, w = shape
    (x0, y0), (x1, y1) = to_world(0, h - 1, h, res, origin), to_world(w - 1, 0, h, res, origin)
    length, width = abs(x1 - x0), abs(y1 - y0)
    lane = width / 4.0
    # OpenDRIVE is right-handed (y left); CARLA mirrors y, so it is given in ROS axes here.
    cx, cy = (x0 + x1) / 2.0, -(y0 + y1) / 2.0
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<OpenDRIVE>
  <header revMajor="1" revMinor="4" name="RobocrossArena" version="1.0" date="" north="0" south="0" east="0" west="0"/>
  <road name="arena" length="{length:.3f}" id="0" junction="-1">
    <planView>
      <geometry s="0" x="{cx - length / 2:.3f}" y="{cy:.3f}" hdg="0" length="{length:.3f}"><line/></geometry>
    </planView>
    <elevationProfile><elevation s="0" a="0" b="0" c="0" d="0"/></elevationProfile>
    <lateralProfile/>
    <lanes>
      <laneSection s="0">
        <left>
          <lane id="2" type="shoulder" level="false"><width sOffset="0" a="{lane:.3f}" b="0" c="0" d="0"/></lane>
          <lane id="1" type="driving" level="false"><width sOffset="0" a="{lane:.3f}" b="0" c="0" d="0"/></lane>
        </left>
        <center><lane id="0" type="none" level="false"/></center>
        <right>
          <lane id="-1" type="driving" level="false"><width sOffset="0" a="{lane:.3f}" b="0" c="0" d="0"/></lane>
          <lane id="-2" type="shoulder" level="false"><width sOffset="0" a="{lane:.3f}" b="0" c="0" d="0"/></lane>
        </right>
      </laneSection>
    </lanes>
  </road>
</OpenDRIVE>
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--map-yaml', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()

    occupied, res, origin = load_occupied(args.map_yaml)
    os.makedirs(args.out, exist_ok=True)
    verts, faces = fence_obj(occupied, res, origin)
    write_obj(os.path.join(args.out, 'fence.obj'), verts, faces)
    write_obj(os.path.join(args.out, 'ground.obj'), *ground_obj(occupied.shape, res, origin))
    with open(os.path.join(args.out, 'arena.xodr'), 'w') as f:
        f.write(arena_xodr(occupied.shape, res, origin))
    print(f'{len(faces) // 2} wall segments -> {args.out}')


if __name__ == '__main__':
    main()
